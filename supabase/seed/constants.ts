// supabase/seed/constants.ts
//
// Deterministic UUIDs for all seed records.
// Fixed IDs make the seed idempotent — running it twice produces the same DB state.
//
// UUID format: 00000000-0000-4{type}-0000-{12-digit sequence}
// Type segments (3rd group):
//   4000 = media_categories
//   4001 = media_assets
//   4002 = gallery_photos
//   4003 = gallery_events (albums)
//   4004 = staff_members
//
// IMPORTANT: Only hex characters are valid in UUIDs: 0-9 and a-f

